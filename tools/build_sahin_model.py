"""Build the Şahin-style ego car with Blender and convert it for Qt Quick 3D.

tools/sahin_blender.py models the car in Blender (bevelled lofted body, real
window and wheel-well openings, lamps, bumpers, plates, interior, wheels) and
exports glTF. PySide6 Balsam converts it, and this script writes the wrapper
QML with the paint/lamp/wheel/suspension contract shared by the Studio cars.
Runs on macOS, Windows and Linux:

    python tools/install_blender.py     # once: verified Blender under .tools/
    python tools/build_sahin_model.py

BLENDER_BIN overrides the Blender executable.
"""
import glob
import os
from pathlib import Path
import platform
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'device_studio/qml/assets/vehicles/sahin'
sys.path.insert(0, str(Path(__file__).resolve().parent))
from install_blender import executable as local_blender  # noqa: E402


def find_blender():
    candidates = [os.environ.get('BLENDER_BIN'), str(local_blender())]
    if platform.system() == 'Darwin':
        candidates.append('/Applications/Blender.app/Contents/MacOS/Blender')
    elif platform.system() == 'Windows':
        candidates += sorted(glob.glob(r'C:\Program Files\Blender Foundation\Blender *\blender.exe'), reverse=True)
    candidates.append(shutil.which('blender'))
    for candidate in candidates:
        if candidate and Path(candidate).is_file():
            return candidate
    raise SystemExit('Blender bulunamadı: önce "python tools/install_blender.py" çalıştırın veya BLENDER_BIN ayarlayın.')


def find_balsam():
    for candidate in (ROOT / '.venv/bin/pyside6-balsam', ROOT / '.venv/Scripts/pyside6-balsam.exe'):
        if candidate.is_file():
            return str(candidate)
    found = shutil.which('pyside6-balsam')
    if not found:
        raise SystemExit('pyside6-balsam bulunamadı: Studio .venv ortamını kurun.')
    return found


QML = '''pragma ComponentBehavior: Bound
import QtQuick
import QtQuick3D

// Generated by tools/build_sahin_model.py from tools/sahin_blender.py: boxy
// 1980s Turkish saloon in metres, +Z forward, ground at y = 0. Same contract
// as the Balsam-imported cars.
Node {
    id: root
    property color paint: "#b5221f"
    property real metallic: 0.15
    property bool braking: false
    property real lamps: 0.35
    property real wheelAngle: 0
    property real steerAngle: 0
    // Positive pitch dives the nose; positive roll leans toward the car's right.
    property real bodyPitch: 0
    property real bodyRoll: 0

    PrincipledMaterial {
        id: paintMaterial
        baseColor: root.paint
        metalness: root.metallic
        roughness: 0.38 - root.metallic * 0.12
        clearcoatAmount: 1
        clearcoatRoughnessAmount: 0.05
    }
    PrincipledMaterial {
        // Tinted, slightly see-through glass shows the cabin like a real car.
        id: glassMaterial
        baseColor: "#121c22"; roughness: 0.03; metalness: 0; specularAmount: 1
        clearcoatAmount: 1; clearcoatRoughnessAmount: 0.02
        alphaMode: PrincipledMaterial.Blend; opacity: 0.62
    }
    PrincipledMaterial { id: trimMaterial; baseColor: "#141517"; roughness: 0.55 }
    PrincipledMaterial { id: underMaterial; baseColor: "#0b0b0c"; roughness: 0.92 }
    PrincipledMaterial { id: chromeMaterial; baseColor: "#dfe3e6"; metalness: 1; roughness: 0.12 }
    PrincipledMaterial { id: grilleMaterial; baseColor: "#1b1e21"; metalness: 0.45; roughness: 0.42 }
    PrincipledMaterial { id: reflectorMaterial; baseColor: "#d8dcdf"; metalness: 1; roughness: 0.06 }
    PrincipledMaterial {
        id: headlightMaterial
        baseColor: "#eef1ee"; roughness: 0.08; metalness: 0.2
        emissiveFactor: Qt.vector3d(root.lamps * 2.4, root.lamps * 2.35, root.lamps * 2.2)
    }
    PrincipledMaterial {
        id: tailMaterial
        baseColor: root.braking ? "#ff3340" : "#6e0d14"; roughness: 0.22
        emissiveFactor: root.braking ? Qt.vector3d(5.5, 0.18, 0.14) : Qt.vector3d(root.lamps * 0.3, 0.005, 0.005)
    }
    PrincipledMaterial { id: signalMaterial; baseColor: "#e48a1c"; roughness: 0.22; emissiveFactor: Qt.vector3d(0.12, 0.05, 0) }
    PrincipledMaterial { id: reverseMaterial; baseColor: "#e9ecea"; roughness: 0.2 }
    PrincipledMaterial { id: plateMaterial; baseColor: "#f4f4ef"; roughness: 0.5 }
    PrincipledMaterial { id: plateTextMaterial; baseColor: "#101010"; roughness: 0.5 }
    PrincipledMaterial { id: plateBandMaterial; baseColor: "#1f4fa8"; roughness: 0.5 }
    PrincipledMaterial { id: interiorMaterial; baseColor: "#2a2b2e"; roughness: 0.85 }
    PrincipledMaterial { id: tyreMaterial; baseColor: "#151616"; roughness: 0.86 }
    PrincipledMaterial { id: rimMaterial; baseColor: "#1c1d20"; metalness: 0.5; roughness: 0.45 }
    PrincipledMaterial { id: hubcapMaterial; baseColor: "#c5cacd"; metalness: 0.9; roughness: 0.26 }

    Node {
        // The body rotates around its suspension centre; wheels stay on the road.
        position: Qt.vector3d(0, 0.45, 0)
        pivot: Qt.vector3d(0, 0.45, 0)
        eulerRotation: Qt.vector3d(root.bodyPitch, 0, -root.bodyRoll)
%(parts)s
    }
    Repeater3D {
        model: [%(wheels)s]
        delegate: Node {
            required property var modelData
            position: Qt.vector3d(modelData[0], %(radius).3f, modelData[1])
            eulerRotation: Qt.vector3d(-root.wheelAngle, modelData[1] > 0 ? root.steerAngle : 0, 0)
%(wheel_parts)s
        }
    }
}
'''


def main():
    blender, balsam = find_blender(), find_balsam()
    with tempfile.TemporaryDirectory(prefix='studio-sahin-') as work:
        work = Path(work)
        glb, out = work / 'sahin.glb', work / 'out'
        result = subprocess.run([blender, '--background', '--factory-startup', '--python',
                                 str(ROOT / 'tools/sahin_blender.py'), '--', str(glb)],
                                # Blender prints UTF-8 paths; Windows' locale codec may not decode them.
                                capture_output=True, encoding='utf-8', errors='replace')
        if result.returncode or not glb.is_file():
            raise SystemExit('Blender modeli üretemedi:\n' + result.stdout[-3000:] + result.stderr[-3000:])
        values = {line.split()[0]: [float(x) for x in line.split()[1:]] for line in result.stdout.splitlines()
                  if line.startswith(('BOUNDS', 'WHEELS'))}
        rear_v, front_v, half_width, height = values['BOUNDS']
        if not (4.0 < front_v - rear_v < 5.0 and half_width < 1.2 and height < 2.0):
            raise SystemExit(f'Blender geçersiz geometri üretti (sınırlar {values["BOUNDS"]}); model yazılmadı.')
        subprocess.run([balsam, str(glb), '-o', str(out)], check=True, capture_output=True)
        source = next(out.glob('*.qml')).read_text()
        nodes = dict(re.findall(r'objectName: "(Sahin\w+)"\s*\n\s*source: "meshes/([^"]+)"', source))
        if DEST.exists():
            shutil.rmtree(DEST)
        (DEST / 'meshes').mkdir(parents=True)
        for mesh in set(nodes.values()):
            shutil.copy2(out / 'meshes' / mesh, DEST / 'meshes' / mesh)

    def model(node, indent):
        material = node.replace('SahinWheel', '').replace('Sahin', '')
        identifier = {'TailLight': 'tail'}.get(material, material[0].lower() + material[1:])
        return f'{indent}Model {{ source: "meshes/{nodes[node]}"; materials: {identifier}Material }}'
    body = [n for n in sorted(nodes) if not n.startswith('SahinWheel')]
    wheel = [n for n in sorted(nodes) if n.startswith('SahinWheel')]
    front, rear, track, radius = values['WHEELS']
    wheels = ', '.join(f'[{x:.3f}, {z:.3f}]' for z in (front, rear) for x in (track, -track))
    (DEST / 'Sahin.qml').write_text(QML % dict(parts='\n'.join(model(n, ' ' * 8) for n in body), wheels=wheels,
                                              radius=radius, wheel_parts='\n'.join(model(n, ' ' * 12) for n in wheel)))
    print(f'Wrote {DEST.relative_to(ROOT)}: {len(body)} body and {len(wheel)} wheel parts.')
    print(f'Vehicle3D spec: length {front_v - rear_v:.3f}, z centre {(front_v + rear_v) / 2:.3f}, '
          f'half width {half_width:.3f}, height {height:.3f}')


if __name__ == '__main__':
    main()
