"""Build the traffic fleet with Blender and convert it for Qt Quick 3D.

tools/traffic_blender.py models five body styles at their real sizes (hatchback,
sedan, SUV, light van, taxi: analytic lofted bodies, painted roofs with framed
glass, conforming lamps, grilles and trim, alloy or steel wheels, TR plates and a
minimal interior) and exports one glTF each. PySide6 Balsam converts them, and
this script writes each wrapper QML with the paint/lamp/wheel/suspension contract
shared by the Studio cars. Runs on macOS, Windows and Linux:

    python tools/install_blender.py     # once: verified Blender under .tools/
    python tools/build_traffic_models.py

BLENDER_BIN overrides the Blender executable.
"""
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

from build_sahin_model import ROOT, find_balsam, find_blender

VEHICLES = ROOT / 'device_studio/qml/assets/vehicles'
STYLES = ('Hatch', 'Sedan', 'Suv', 'Van', 'Taxi')


QML = '''pragma ComponentBehavior: Bound
import QtQuick
import QtQuick3D

// Generated by tools/build_traffic_models.py from tools/traffic_blender.py:
// %(what)s in metres, +Z forward, ground at y = 0.
// Same contract as the other Studio cars; no badges or logos.
Node {
    id: root
    property color paint: "%(paint)s"
    property real metallic: 0.4
    property bool braking: false
    property real lamps: 0.35
    property real wheelAngle: 0
    // Positive pitch dives the nose; positive roll leans toward the car's right.
    property real bodyPitch: 0
    property real bodyRoll: 0

    PrincipledMaterial {
        id: paintMaterial
        baseColor: root.paint
        metalness: root.metallic
        roughness: 0.3 - root.metallic * 0.1
        clearcoatAmount: 1
        clearcoatRoughnessAmount: 0.05
    }
    PrincipledMaterial {
        // Lightly tinted glass: the cabin shows through, the sky reflects.
        id: glassMaterial
        baseColor: "#0b1116"; roughness: 0.03; metalness: 0; specularAmount: 0.9
        clearcoatAmount: 0.6; clearcoatRoughnessAmount: 0.02
        alphaMode: PrincipledMaterial.Blend; opacity: 0.82
    }
    PrincipledMaterial { id: glossBlackMaterial; baseColor: "#08090a"; roughness: 0.14; clearcoatAmount: 1; clearcoatRoughnessAmount: 0.05 }
    PrincipledMaterial { id: trimMaterial; baseColor: "#141517"; roughness: 0.62 }
    PrincipledMaterial { id: underMaterial; baseColor: "#0b0b0c"; roughness: 0.92 }
    PrincipledMaterial { id: lampDarkMaterial; baseColor: "#16191c"; metalness: 0.7; roughness: 0.16; clearcoatAmount: 1 }
    PrincipledMaterial {
        id: headlightMaterial
        baseColor: "#eef3f7"; roughness: 0.08; metalness: 0.1
        emissiveFactor: Qt.vector3d(root.lamps * 3.0, root.lamps * 3.1, root.lamps * 3.3)
    }
    PrincipledMaterial {
        id: tailMaterial
        baseColor: root.braking ? "#ff3340" : "#6a0b14"; roughness: 0.2
        emissiveFactor: root.braking ? Qt.vector3d(6.0, 0.2, 0.15) : Qt.vector3d(root.lamps * 1.1, 0.01, 0.01)
    }
    PrincipledMaterial { id: signalMaterial; baseColor: "#e48a1c"; roughness: 0.22; emissiveFactor: Qt.vector3d(0.12, 0.05, 0) }
    PrincipledMaterial { id: reflexMaterial; baseColor: "#4a080d"; roughness: 0.3 }
    PrincipledMaterial { id: reflectorMaterial; baseColor: "#d8dcdf"; metalness: 1; roughness: 0.06 }
    PrincipledMaterial { id: chromeMaterial; baseColor: "#c9ced3"; metalness: 1; roughness: 0.12 }
    PrincipledMaterial { id: plateMaterial; baseColor: "#f4f4ef"; roughness: 0.5 }
    PrincipledMaterial { id: plateTextMaterial; baseColor: "#101010"; roughness: 0.5 }
    PrincipledMaterial { id: plateBandMaterial; baseColor: "#1f4fa8"; roughness: 0.5 }
    PrincipledMaterial { id: interiorMaterial; baseColor: "#1d1e21"; roughness: 0.8 }
    PrincipledMaterial {
        // Taxi roof sign, lit from inside.
        id: signBodyMaterial
        baseColor: "#f6f1dc"; roughness: 0.35
        emissiveFactor: Qt.vector3d(0.35 + root.lamps, 0.33 + root.lamps, 0.25 + root.lamps * 0.6)
    }
    PrincipledMaterial { id: signTextMaterial; baseColor: "#111111"; roughness: 0.5 }
    PrincipledMaterial { id: tyreMaterial; baseColor: "#141515"; roughness: 0.86 }
    PrincipledMaterial { id: rimMaterial; baseColor: "#aeb4ba"; metalness: 0.9; roughness: 0.28 }
    PrincipledMaterial { id: steelMaterial; baseColor: "#1e2124"; metalness: 0.5; roughness: 0.5 }
    PrincipledMaterial { id: capMaterial; baseColor: "#8d949b"; metalness: 0.75; roughness: 0.32 }

    Node {
        // The body rotates around its suspension centre; wheels stay on the road.
        position: Qt.vector3d(0, 0.45, 0)
        pivot: Qt.vector3d(0, 0.45, 0)
        eulerRotation: Qt.vector3d(root.bodyPitch, 0, -root.bodyRoll)
%(parts)s
    }
    Repeater3D {
        model: [%(wheels)s]
        delegate: Node {
            required property var modelData
            position: Qt.vector3d(modelData[0], %(radius).3f, modelData[1])
            eulerRotation.x: -root.wheelAngle
%(wheel_parts)s
        }
    }
}
'''

WHAT = {'Hatch': 'Renault Clio class five-door hatchback', 'Sedan': 'Fiat Egea class sedan',
        'Suv': 'Togg T10X / Hyundai Tucson class SUV', 'Van': 'Fiat Doblo class light van',
        'Taxi': 'yellow Istanbul sedan taxi with a roof sign'}
PAINT = {'Hatch': '#2a5d9c', 'Sedan': '#b03030', 'Suv': '#4a5560', 'Van': '#e8e8e6', 'Taxi': '#f2c12e'}


def main():
    blender, balsam = find_blender(), find_balsam()
    with tempfile.TemporaryDirectory(prefix='studio-traffic-') as work:
        work = Path(work)
        result = subprocess.run([blender, '--background', '--factory-startup', '--python',
                                 str(ROOT / 'tools/traffic_blender.py'), '--', str(work)],
                                # Blender prints UTF-8 paths; Windows' locale codec may not decode them.
                                capture_output=True, encoding='utf-8', errors='replace')
        if result.returncode or not all((work / f'{style}.glb').is_file() for style in STYLES):
            raise SystemExit('Blender modelleri üretemedi:\n' + result.stdout[-3000:] + result.stderr[-3000:])
        values = {}
        for line in result.stdout.splitlines():
            words = line.split()
            if len(words) > 2 and words[0] in STYLES and words[1] in ('BOUNDS', 'WHEELS', 'INDICATORS'):
                values[words[0], words[1]] = [float(x) for x in words[2:]]
        for style in STYLES:
            rear_v, front_v, _, height, half_width = values[style, 'BOUNDS']
            if not (3.8 < front_v - rear_v < 5.0 and half_width < 1.2 and height < 2.1):
                raise SystemExit(f'Blender geçersiz geometri üretti ({style}: {values[style, "BOUNDS"]}); model yazılmadı.')
            out = work / style
            subprocess.run([balsam, str(work / f'{style}.glb'), '-o', str(out)], check=True, capture_output=True)
            source = next(out.glob('*.qml')).read_text()
            nodes = dict(re.findall(r'objectName: "(%s\w+)"\s*\n\s*source: "meshes/([^"]+)"' % style, source))
            dest = VEHICLES / style.lower()
            if dest.exists():
                shutil.rmtree(dest)
            (dest / 'meshes').mkdir(parents=True)
            for mesh in set(nodes.values()):
                shutil.copy2(out / 'meshes' / mesh, dest / 'meshes' / mesh)

            def model(node, indent):
                material = node[len(style):].replace('Wheel', '', 1) if node.startswith(style + 'Wheel') else node[len(style):]
                identifier = {'TailLight': 'tail'}.get(material, material[0].lower() + material[1:])
                return f'{indent}Model {{ source: "meshes/{nodes[node]}"; materials: {identifier}Material }}'
            body = [n for n in sorted(nodes) if not n.startswith(style + 'Wheel')]
            wheel = [n for n in sorted(nodes) if n.startswith(style + 'Wheel')]
            front, rear, track, radius = values[style, 'WHEELS']
            wheels = ', '.join(f'[{x:.3f}, {z:.3f}]' for z in (front, rear) for x in (track, -track))
            (dest / f'{style}.qml').write_text(QML % dict(
                what=WHAT[style], paint=PAINT[style], parts='\n'.join(model(n, ' ' * 8) for n in body), wheels=wheels,
                radius=radius, wheel_parts='\n'.join(model(n, ' ' * 12) for n in wheel)))
            lamp = values[style, 'INDICATORS']
            print(f'Wrote {dest.relative_to(ROOT)}: {len(body)} body and {len(wheel)} wheel parts.')
            print(f'  Vehicle3D spec: [{front_v - rear_v:.3f}, {(front_v + rear_v) / 2:.3f}, {half_width:.3f}, {height:.3f}, '
                  + ', '.join(f'{x:.3f}' for x in lamp) + ']')


if __name__ == '__main__':
    main()
