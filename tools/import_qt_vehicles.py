"""Convert the existing CC0 FBX cars for Studio's embedded Qt Quick 3D scene."""
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'godot/adas_drive/assets/vehicles/quaternius'
DEST = ROOT / 'device_studio/qml/assets/vehicles'


def main():
    balsam = ROOT / '.venv/bin/pyside6-balsam'
    for model, folder in [('NormalCar1', 'sedan'), ('SUV', 'suv'), ('SportsCar', 'sports'), ('Taxi', 'taxi')]:
        target = DEST / folder
        target.mkdir(parents=True, exist_ok=True)
        subprocess.run([str(balsam), str(SOURCE / (model + '.fbx')), '-o', str(target)], check=True)
        qml = target / (('Suv' if model == 'SUV' else model) + '.qml')
        text = qml.read_text()
        text = text.replace('    // Resources', '''    property color paint: "#42bfa7"
    property bool braking: false
    property real wheelAngle: 0
    // Source FBX uses centimetres; the scene uses metres.
    scale: Qt.vector3d(0.01, 0.01, 0.01)

    // Resources''')
        def material(match):
            block = match[0]
            name = re.search(r'objectName: "([^"]+)"', block)[1]
            if name in ('Blue', 'White', 'Orange', 'Yellow'):
                block = re.sub(r'baseColor: .*', 'baseColor: root.paint', block)
                block = re.sub(r'roughness: .*', 'roughness: 0.25\n        metalness: 0.35\n        clearcoatAmount: 0.65', block)
            elif name == 'Windows':
                block = re.sub(r'baseColor: .*', 'baseColor: "#294657"', block)
                block = re.sub(r'roughness: .*', 'roughness: 0.16\n        metalness: 0.6', block)
            elif name == 'Headlights':
                block = re.sub(r'baseColor: .*', 'baseColor: "#fff3d2"\n        emissiveFactor: Qt.vector3d(0.3, 0.28, 0.2)', block)
            elif name == 'TailLights':
                block = re.sub(r'baseColor: .*', 'baseColor: root.braking ? "#ff2538" : "#831927"\n        emissiveFactor: root.braking ? Qt.vector3d(2, 0.03, 0.03) : Qt.vector3d(0.05, 0, 0)', block)
            return block
        text = re.sub(r'    PrincipledMaterial \{.*?\n    \}', material, text, flags=re.S)
        text = re.sub(r'(objectName: "[^"]*Wheel[^"]*"\n)', r'\1            eulerRotation.x: root.wheelAngle\n', text)
        qml.write_text(text)
    shutil.copy2(SOURCE / 'LICENSE.txt', DEST / 'LICENSE.txt')
    (DEST / 'README.md').write_text('''# Embedded 3D cars

Quaternius Racing Kit, CC0. Original FBX and license are preserved under
`godot/adas_drive/assets/vehicles/quaternius/`. These meshes are generated by
`tools/import_qt_vehicles.py` with the installed PySide6 Balsam importer.
Material bindings add paint, brake lamps and rotating wheels. Source centimetres
are converted to metres; source +Z is rotated toward the road's -Z at runtime.
''')


if __name__ == '__main__':
    main()
