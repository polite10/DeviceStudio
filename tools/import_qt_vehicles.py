"""Convert the existing CC0 FBX cars for Studio's embedded Qt Quick 3D scene."""
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'godot/adas_drive/assets/vehicles/quaternius'
DEST = ROOT / 'device_studio/qml/assets/vehicles'
MODELS = [('NormalCar1', 'sedan', 'NormalCar1'), ('SUV', 'suv', 'Suv'), ('SportsCar', 'sports', 'SportsCar'),
          ('Taxi', 'taxi', 'Taxi'), ('SportsCar2', 'sports2', 'SportsCar2')]
PAINT = ('Blue', 'White', 'Orange', 'Yellow')
MATERIALS = {
    'Windows': '''baseColor: "#0d151b"
        roughness: 0.05
        metalness: 0
        specularAmount: 1
        clearcoatAmount: 1
        clearcoatRoughnessAmount: 0.02''',
    'Headlights': '''baseColor: "#f6f3ea"
        emissiveFactor: Qt.vector3d(root.lamps * 2.6, root.lamps * 2.5, root.lamps * 2.3)
        roughness: 0.2''',
    'TailLights': '''baseColor: root.braking ? "#ff3340" : "#8a121c"
        emissiveFactor: root.braking ? Qt.vector3d(5.5, 0.18, 0.14) : Qt.vector3d(root.lamps * 0.8, 0.01, 0.01)
        roughness: 0.25''',
    'Grey': '''baseColor: "#8a8f94"
        metalness: 0.8
        roughness: 0.32''',
    'Black': '''baseColor: "#121314"
        roughness: 0.8''',
}


def main():
    balsam = ROOT / '.venv/bin/pyside6-balsam'
    for model, folder, name in MODELS:
        target = DEST / folder
        target.mkdir(parents=True, exist_ok=True)
        subprocess.run([str(balsam), str(SOURCE / (model + '.fbx')), '-o', str(target)], check=True)
        qml = target / (name + '.qml')
        text = qml.read_text()
        text = text.replace('    // Resources', '''    property color paint: "#42bfa7"
    property real metallic: 0.5
    property bool braking: false
    // Daytime running and tail lamp glow; brake lamps are always brighter.
    property real lamps: 0.35
    property real wheelAngle: 0
    // Suspension: the body pitches/rolls around its centre, wheels stay grounded.
    property real bodyPitch: 0
    property real bodyRoll: 0
    // Source FBX uses centimetres; the scene uses metres.
    scale: Qt.vector3d(0.01, 0.01, 0.01)

    // Resources''')

        def material(match):
            block = match[0]
            material_name = re.search(r'objectName: "([^"]+)"', block)[1]
            body = re.search(r'objectName: "[^"]+"\n(.*?)\n    \}', block, re.S)[1]
            if material_name in PAINT:
                replacement = '''baseColor: root.paint
        metalness: root.metallic
        roughness: 0.42 - root.metallic * 0.12
        clearcoatAmount: 1
        clearcoatRoughnessAmount: 0.04'''
            elif material_name in MATERIALS:
                replacement = MATERIALS[material_name]
            else:
                return block
            return block.replace(body, '        ' + replacement)
        text = re.sub(r'    PrincipledMaterial \{.*?\n    \}', material, text, flags=re.S)
        text = re.sub(r'(objectName: "[^"]*Wheel[^"]*"\n)', r'\1            eulerRotation.x: root.wheelAngle\n', text)
        # Qt applies pivot as T(position)·R·T(-pivot): matching them rotates the
        # body about its centre without moving it.
        text = text.replace(f'objectName: "{model}"\n',
                            f'objectName: "{model}"\n            position: Qt.vector3d(0, 0, 45)\n'
                            '            pivot: Qt.vector3d(0, 0, 45)\n'
                            '            eulerRotation: Qt.vector3d(root.bodyPitch, root.bodyRoll, 0)\n')
        qml.write_text(text)
    shutil.copy2(SOURCE / 'LICENSE.txt', DEST / 'LICENSE.txt')
    (DEST / 'README.md').write_text('''# Embedded 3D cars

Quaternius Racing Kit, CC0. Original FBX and license are preserved under
`godot/adas_drive/assets/vehicles/quaternius/`. These meshes are generated by
`tools/import_qt_vehicles.py` with the installed PySide6 Balsam importer.
Material bindings add clear-coated paint, tinted glass, lamps, brake lamps,
rotating wheels and body pitch/roll. Source centimetres are converted to
metres; source +Z is rotated toward the road's -Z at runtime.
''')


if __name__ == '__main__':
    main()
