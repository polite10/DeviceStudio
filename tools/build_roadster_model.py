"""Build the 2028 Roadster style flying ego car with Blender and convert it for Qt Quick 3D.

tools/roadster_blender.py models the car in Blender (polygon-section wedge body,
gold glass T-top canopy, hidden headlamps, light bars, suction fans, ten cold gas
nozzles, pop-up wing, aero wheels) and exports glTF. PySide6 Balsam converts it,
and this script writes the wrapper QML: the paint/lamp/wheel/suspension contract
shared by the Studio cars plus `thrust`, `boost`, `retro` and `side` (frosting
nozzles), `wing` (raised tail wing) and the nozzle exits that Drive3DView emits
its compressed-air jet particles from. Runs on macOS, Windows and Linux:

    python tools/install_blender.py     # once: verified Blender under .tools/
    python tools/build_roadster_model.py

BLENDER_BIN overrides the Blender executable.
"""
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

from build_sahin_model import ROOT, find_balsam, find_blender

DEST = ROOT / 'device_studio/qml/assets/vehicles/roadster'


QML = '''pragma ComponentBehavior: Bound
import QtQuick
import QtQuick3D

// Generated by tools/build_roadster_model.py from tools/roadster_blender.py:
// 2028 Tesla Roadster style flying hypercar in metres, +Z forward, ground at y = 0.
// Same contract as the other Studio cars plus thrust, boost and wing; no badges or logos.
Node {
    id: root
    property color paint: "#eef0f1"
    property real metallic: 0.05
    property bool braking: false
    property real lamps: 0.35
    property real wheelAngle: 0
    // Positive pitch dives the nose; positive roll leans toward the car's right.
    property real bodyPitch: 0
    property real bodyRoll: 0
    // 0..1: lift nozzles behind the wheels and the nose yaw nozzles fire.
    property real thrust: 0
    // 0..1: the four rear nozzles fire backwards.
    property real boost: 0
    // 0..1: the nose nozzles brake in the air; -1..1: sideways push to the car's right.
    property real retro: 0
    property real side: 0
    // 0 flush with the tail .. 1 raised on its stabilisers.
    property real wing: 0
    // Nozzle exits in metres, this frame: four lift nozzles under the floor, the
    // nose pair that pushes sideways, the four rear ones. Drive3DView emits the jets.
    readonly property var nozzles: ({lift: [%(lift)s], yaw: [%(yaw)s], boost: [%(boost)s]})

    PrincipledMaterial {
        id: paintMaterial
        baseColor: root.paint
        metalness: root.metallic
        roughness: 0.26
        clearcoatAmount: 1
        clearcoatRoughnessAmount: 0.03
    }
    PrincipledMaterial {
        // Gold tinted glass, like a spacesuit visor.
        id: glassMaterial
        baseColor: "#6a5218"; roughness: 0.04; metalness: 0.8; specularAmount: 1
        clearcoatAmount: 1; clearcoatRoughnessAmount: 0.02
        alphaMode: PrincipledMaterial.Blend; opacity: 0.9
    }
    PrincipledMaterial { id: glossBlackMaterial; baseColor: "#08090a"; roughness: 0.14; clearcoatAmount: 1; clearcoatRoughnessAmount: 0.05 }
    PrincipledMaterial { id: trimMaterial; baseColor: "#121315"; roughness: 0.6 }
    PrincipledMaterial { id: underMaterial; baseColor: "#0b0b0c"; roughness: 0.92 }
    PrincipledMaterial { id: lampDarkMaterial; baseColor: "#16191c"; metalness: 0.7; roughness: 0.16; clearcoatAmount: 1 }
    PrincipledMaterial {
        id: headlightMaterial
        baseColor: "#f1f5f8"; roughness: 0.08; metalness: 0.1
        emissiveFactor: Qt.vector3d(root.lamps * 3.4, root.lamps * 3.5, root.lamps * 3.7)
    }
    PrincipledMaterial {
        id: tailMaterial
        baseColor: root.braking ? "#ff3340" : "#6a0b14"; roughness: 0.2
        emissiveFactor: root.braking ? Qt.vector3d(6.5, 0.2, 0.15) : Qt.vector3d(root.lamps * 1.6, 0.02, 0.02)
    }
    PrincipledMaterial { id: signalMaterial; baseColor: "#e48a1c"; roughness: 0.22; emissiveFactor: Qt.vector3d(0.15, 0.06, 0) }
    PrincipledMaterial { id: fanMaterial; baseColor: "#1b1f24"; metalness: 0.8; roughness: 0.3 }
    PrincipledMaterial {
        // Expanding cold air frosts the nozzle lips; nothing burns, nothing glows.
        id: thrusterMaterial
        readonly property real flow: Math.max(root.thrust, root.boost, root.retro, Math.abs(root.side))
        baseColor: Qt.tint("#2a3037", Qt.rgba(0.86, 0.9, 0.94, 0.55 * flow)); metalness: 0.9 - 0.5 * flow; roughness: 0.25 + 0.4 * flow
    }
    PrincipledMaterial { id: wingMaterial; baseColor: root.paint; metalness: root.metallic; roughness: 0.26; clearcoatAmount: 1 }
    PrincipledMaterial { id: plateMaterial; baseColor: "#f4f4ef"; roughness: 0.5 }
    PrincipledMaterial { id: plateTextMaterial; baseColor: "#101010"; roughness: 0.5 }
    PrincipledMaterial { id: plateBandMaterial; baseColor: "#1f4fa8"; roughness: 0.5 }
    PrincipledMaterial { id: interiorMaterial; baseColor: "#1d1e21"; roughness: 0.8 }
    PrincipledMaterial { id: tyreMaterial; baseColor: "#141515"; roughness: 0.86 }
    PrincipledMaterial { id: rimMaterial; baseColor: "#1c1d20"; metalness: 0.5; roughness: 0.45 }
    PrincipledMaterial { id: aeroMaterial; baseColor: "#24272b"; metalness: 0.7; roughness: 0.3 }
    PrincipledMaterial { id: aeroAccentMaterial; baseColor: "#b9c0c7"; metalness: 0.9; roughness: 0.25 }
    PrincipledMaterial { id: capMaterial; baseColor: "#0c0d0f"; roughness: 0.2; clearcoatAmount: 1 }

    Node {
        // The body rotates around its suspension centre; wheels stay on the road.
        position: Qt.vector3d(0, 0.45, 0)
        pivot: Qt.vector3d(0, 0.45, 0)
        eulerRotation: Qt.vector3d(root.bodyPitch, 0, -root.bodyRoll)
%(parts)s
        Node {
            // The tail section rises on its stabiliser fins.
            y: root.wing * 0.2
%(wing)s
        }
    }
    Repeater3D {
        model: [%(wheels)s]
        delegate: Node {
            required property var modelData
            position: Qt.vector3d(modelData[0], %(radius).3f, modelData[1])
            eulerRotation.x: -root.wheelAngle
%(wheel_parts)s
        }
    }
}
'''


def main():
    blender, balsam = find_blender(), find_balsam()
    with tempfile.TemporaryDirectory(prefix='studio-roadster-') as work:
        work = Path(work)
        glb, out = work / 'roadster.glb', work / 'out'
        result = subprocess.run([blender, '--background', '--factory-startup', '--python',
                                 str(ROOT / 'tools/roadster_blender.py'), '--', str(glb)],
                                # Blender prints UTF-8 paths; Windows' locale codec may not decode them.
                                capture_output=True, encoding='utf-8', errors='replace')
        if result.returncode or not glb.is_file():
            raise SystemExit('Blender modeli üretemedi:\n' + result.stdout[-3000:] + result.stderr[-3000:])
        lines = {line.split()[0]: line.split()[1:] for line in result.stdout.splitlines()
                 if line.startswith(('BOUNDS', 'WHEELS', 'INDICATORS', 'LIFT', 'BOOST', 'YAW'))}
        rear_v, front_v, half_width, height = map(float, lines['BOUNDS'])
        if not (4.0 < front_v - rear_v < 5.0 and half_width < 1.2 and height < 2.0):
            raise SystemExit(f'Blender geçersiz geometri üretti (sınırlar {lines["BOUNDS"]}); model yazılmadı.')
        subprocess.run([balsam, str(glb), '-o', str(out)], check=True, capture_output=True)
        source = next(out.glob('*.qml')).read_text()
        nodes = dict(re.findall(r'objectName: "(Roadster\w+)"\s*\n\s*source: "meshes/([^"]+)"', source))
        if DEST.exists():
            shutil.rmtree(DEST)
        (DEST / 'meshes').mkdir(parents=True)
        for mesh in set(nodes.values()):
            shutil.copy2(out / 'meshes' / mesh, DEST / 'meshes' / mesh)

    def model(node, indent):
        material = node.replace('RoadsterWheel', '').replace('Roadster', '')
        identifier = {'TailLight': 'tail'}.get(material, material[0].lower() + material[1:])
        return f'{indent}Model {{ source: "meshes/{nodes[node]}"; materials: {identifier}Material }}'

    def points(name):
        # The body node's pivot cancels its offset: nozzles keep model coordinates.
        return ', '.join(f'[{float(u):.3f}, {float(w):.3f}, {float(v):.3f}]'
                         for u, w, v in (item.split(',') for item in lines[name]))
    body = [n for n in sorted(nodes) if not n.startswith('RoadsterWheel') and n != 'RoadsterWing']
    wheel = [n for n in sorted(nodes) if n.startswith('RoadsterWheel')]
    front, rear, track, radius = map(float, lines['WHEELS'])
    wheels = ', '.join(f'[{x:.3f}, {z:.3f}]' for z in (front, rear) for x in (track, -track))
    (DEST / 'Roadster.qml').write_text(QML % dict(
        parts='\n'.join(model(n, ' ' * 8) for n in body), wing=model('RoadsterWing', ' ' * 12),
        lift=points('LIFT'), yaw=points('YAW'), boost=points('BOOST'), wheels=wheels, radius=radius,
        wheel_parts='\n'.join(model(n, ' ' * 12) for n in wheel)))
    print(f'Wrote {DEST.relative_to(ROOT)}: {len(body) + 1} body and {len(wheel)} wheel parts.')
    lamp = ', '.join(f'{float(x):.3f}' for x in lines['INDICATORS'])
    print(f'Vehicle3D spec: [{front_v - rear_v:.3f}, {(front_v + rear_v) / 2:.3f}, {half_width:.3f}, {height:.3f}, {lamp}]')


if __name__ == '__main__':
    main()
