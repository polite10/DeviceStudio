"""Build the Model 3-style ego car with Blender and convert it for Qt Quick 3D.

tools/model3_blender.py models the car in Blender (analytic lofted body and
glass canopy, conforming lamps, pillars and trim, aero wheels, plates and a
minimal interior) and exports glTF. PySide6 Balsam converts it, and this
script writes the wrapper QML with the paint/lamp/wheel/suspension contract
shared by the Studio cars. Runs on macOS, Windows and Linux:

    python tools/install_blender.py     # once: verified Blender under .tools/
    python tools/build_model3_model.py

BLENDER_BIN overrides the Blender executable.
"""
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

from build_sahin_model import ROOT, find_balsam, find_blender

DEST = ROOT / 'device_studio/qml/assets/vehicles/model3'


QML = '''pragma ComponentBehavior: Bound
import QtQuick
import QtQuick3D

// Generated by tools/build_model3_model.py from tools/model3_blender.py:
// Tesla Model 3 style electric saloon in metres, +Z forward, ground at y = 0.
// Same contract as the other Studio cars; no badges or logos.
Node {
    id: root
    property color paint: "#e8eaec"
    property real metallic: 0.2
    property bool braking: false
    property real lamps: 0.35
    property real wheelAngle: 0
    property real steerAngle: 0
    // Positive pitch dives the nose; positive roll leans toward the car's right.
    property real bodyPitch: 0
    property real bodyRoll: 0

    PrincipledMaterial {
        id: paintMaterial
        baseColor: root.paint
        metalness: root.metallic
        roughness: 0.3 - root.metallic * 0.1
        clearcoatAmount: 1
        clearcoatRoughnessAmount: 0.04
    }
    PrincipledMaterial {
        // Deeply tinted canopy glass, as on the real glass roof; the cabin
        // still shows through the side windows.
        id: glassMaterial
        baseColor: "#05080b"; roughness: 0.04; metalness: 0; specularAmount: 0.8
        clearcoatAmount: 0.5; clearcoatRoughnessAmount: 0.02
        alphaMode: PrincipledMaterial.Blend; opacity: 0.9
    }
    PrincipledMaterial { id: glossBlackMaterial; baseColor: "#08090a"; roughness: 0.14; clearcoatAmount: 1; clearcoatRoughnessAmount: 0.05 }
    PrincipledMaterial { id: trimMaterial; baseColor: "#121315"; roughness: 0.6 }
    PrincipledMaterial { id: underMaterial; baseColor: "#0b0b0c"; roughness: 0.92 }
    PrincipledMaterial { id: lampDarkMaterial; baseColor: "#16191c"; metalness: 0.7; roughness: 0.16; clearcoatAmount: 1 }
    PrincipledMaterial {
        id: headlightMaterial
        baseColor: "#f1f5f8"; roughness: 0.08; metalness: 0.1
        emissiveFactor: Qt.vector3d(root.lamps * 3.2, root.lamps * 3.3, root.lamps * 3.5)
    }
    PrincipledMaterial {
        id: tailMaterial
        baseColor: root.braking ? "#ff3340" : "#5e0a12"; roughness: 0.2
        emissiveFactor: root.braking ? Qt.vector3d(6.0, 0.2, 0.15) : Qt.vector3d(root.lamps * 0.9, 0.01, 0.01)
    }
    PrincipledMaterial { id: reflexMaterial; baseColor: "#4a080d"; roughness: 0.3 }
    PrincipledMaterial { id: reflectorMaterial; baseColor: "#d8dcdf"; metalness: 1; roughness: 0.06 }
    PrincipledMaterial { id: plateMaterial; baseColor: "#f4f4ef"; roughness: 0.5 }
    PrincipledMaterial { id: plateTextMaterial; baseColor: "#101010"; roughness: 0.5 }
    PrincipledMaterial { id: plateBandMaterial; baseColor: "#1f4fa8"; roughness: 0.5 }
    PrincipledMaterial { id: interiorMaterial; baseColor: "#1d1e21"; roughness: 0.8 }
    PrincipledMaterial { id: screenMaterial; baseColor: "#0c1118"; roughness: 0.1; emissiveFactor: Qt.vector3d(0.05, 0.09, 0.15) }
    PrincipledMaterial { id: tyreMaterial; baseColor: "#141515"; roughness: 0.86 }
    PrincipledMaterial { id: rimMaterial; baseColor: "#1c1d20"; metalness: 0.5; roughness: 0.45 }
    PrincipledMaterial { id: aeroMaterial; baseColor: "#3a3e43"; metalness: 0.55; roughness: 0.36 }
    PrincipledMaterial { id: aeroAccentMaterial; baseColor: "#9aa1a8"; metalness: 0.85; roughness: 0.28 }
    PrincipledMaterial { id: capMaterial; baseColor: "#0c0d0f"; roughness: 0.2; clearcoatAmount: 1 }

    Node {
        // The body rotates around its suspension centre; wheels stay on the road.
        position: Qt.vector3d(0, 0.45, 0)
        pivot: Qt.vector3d(0, 0.45, 0)
        eulerRotation: Qt.vector3d(root.bodyPitch, 0, -root.bodyRoll)
%(parts)s
    }
    Repeater3D {
        model: [%(wheels)s]
        delegate: Node {
            required property var modelData
            position: Qt.vector3d(modelData[0], %(radius).3f, modelData[1])
            eulerRotation: Qt.vector3d(-root.wheelAngle, modelData[1] > 0 ? root.steerAngle : 0, 0)
%(wheel_parts)s
        }
    }
}
'''


def main():
    blender, balsam = find_blender(), find_balsam()
    with tempfile.TemporaryDirectory(prefix='studio-model3-') as work:
        work = Path(work)
        glb, out = work / 'model3.glb', work / 'out'
        result = subprocess.run([blender, '--background', '--factory-startup', '--python',
                                 str(ROOT / 'tools/model3_blender.py'), '--', str(glb)],
                                # Blender prints UTF-8 paths; Windows' locale codec may not decode them.
                                capture_output=True, encoding='utf-8', errors='replace')
        if result.returncode or not glb.is_file():
            raise SystemExit('Blender modeli üretemedi:\n' + result.stdout[-3000:] + result.stderr[-3000:])
        values = {line.split()[0]: [float(x) for x in line.split()[1:]] for line in result.stdout.splitlines()
                  if line.startswith(('BOUNDS', 'WHEELS', 'INDICATORS'))}
        rear_v, front_v, half_width, height = values['BOUNDS']
        if not (4.0 < front_v - rear_v < 5.0 and half_width < 1.2 and height < 2.0):
            raise SystemExit(f'Blender geçersiz geometri üretti (sınırlar {values["BOUNDS"]}); model yazılmadı.')
        subprocess.run([balsam, str(glb), '-o', str(out)], check=True, capture_output=True)
        source = next(out.glob('*.qml')).read_text()
        nodes = dict(re.findall(r'objectName: "(Model3\w+)"\s*\n\s*source: "meshes/([^"]+)"', source))
        if DEST.exists():
            shutil.rmtree(DEST)
        (DEST / 'meshes').mkdir(parents=True)
        for mesh in set(nodes.values()):
            shutil.copy2(out / 'meshes' / mesh, DEST / 'meshes' / mesh)

    def model(node, indent):
        material = node.replace('Model3Wheel', '').replace('Model3', '')
        identifier = {'TailLight': 'tail'}.get(material, material[0].lower() + material[1:])
        return f'{indent}Model {{ source: "meshes/{nodes[node]}"; materials: {identifier}Material }}'
    body = [n for n in sorted(nodes) if not n.startswith('Model3Wheel')]
    wheel = [n for n in sorted(nodes) if n.startswith('Model3Wheel')]
    front, rear, track, radius = values['WHEELS']
    wheels = ', '.join(f'[{x:.3f}, {z:.3f}]' for z in (front, rear) for x in (track, -track))
    (DEST / 'Model3.qml').write_text(QML % dict(parts='\n'.join(model(n, ' ' * 8) for n in body), wheels=wheels,
                                                radius=radius, wheel_parts='\n'.join(model(n, ' ' * 12) for n in wheel)))
    print(f'Wrote {DEST.relative_to(ROOT)}: {len(body)} body and {len(wheel)} wheel parts.')
    lamp = values['INDICATORS']
    print(f'Vehicle3D spec: [{front_v - rear_v:.3f}, {(front_v + rear_v) / 2:.3f}, {half_width:.3f}, {height:.3f}, '
          + ', '.join(f'{x:.3f}' for x in lamp) + ']')


if __name__ == '__main__':
    main()
